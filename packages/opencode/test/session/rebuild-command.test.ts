// /rebuild is registered with template "$ARGUMENTS" (src/command/index.ts:167-176). These tests record the
// exact text the model receives for /rebuild, from the request bodies the scripted LLM server saw.
const requestText = (body: Record<string, unknown>) => {
  const messages = (body["messages"] as { role: string; content: unknown }[] | undefined) ?? []
  return messages.map((m) => ({
    role: m.role,
    text: typeof m.content === "string" ? m.content : JSON.stringify(m.content),
  }))
}

describe("/rebuild", () => {
  it.instance(
    "with no arguments the model request holds the system prompt and no user message",
    () =>
      Effect.gen(function* () {
        const { llm } = yield* useServerConfig(providerCfg)
        const prompt = yield* SessionPrompt.Service
        const sessions = yield* Session.Service
        const chat = yield* sessions.create({ title: "rebuild" })
        yield* llm.text("done")
        const result = yield* prompt
          .command({ sessionID: chat.id, command: "rebuild", arguments: "", agent: "build" } as never)
          .pipe(Effect.exit)
        const requests = (yield* llm.inputs).map(requestText)

        expect(Exit.isSuccess(result)).toBe(true)
        expect(requests).toHaveLength(1)
        expect(requests[0]!.map((m) => m.role)).toEqual(["system"])
      }),
    30_000,
  )

  it.instance(
    "with arguments the model receives exactly the arguments as the user message",
    () =>
      Effect.gen(function* () {
        const { llm } = yield* useServerConfig(providerCfg)
        const prompt = yield* SessionPrompt.Service
        const sessions = yield* Session.Service
        const chat = yield* sessions.create({ title: "rebuild args" })
        yield* llm.text("done")
        yield* prompt.command({ sessionID: chat.id, command: "rebuild", arguments: "now please", agent: "build" } as never)
        const requests = (yield* llm.inputs).map(requestText)

        expect(requests).toHaveLength(1)
        expect(requests[0]!.filter((m) => m.role === "user")).toEqual([{ role: "user", text: "now please" }])
      }),
    30_000,
  )

  it.instance(
    "does not run a checkpoint rebuild: no checkpoint or compaction message is written",
    () =>
      Effect.gen(function* () {
        const { llm } = yield* useServerConfig(providerCfg)
        const prompt = yield* SessionPrompt.Service
        const sessions = yield* Session.Service
        const chat = yield* sessions.create({ title: "rebuild none" })
        yield* llm.text("done")
        yield* prompt.command({ sessionID: chat.id, command: "rebuild", arguments: "go", agent: "build" } as never)
        const msgs = yield* MessageV2.filterCompactedEffect(chat.id)
        const parts = msgs.flatMap((m) => m.parts.map((p) => p.type))

        expect(parts).not.toContain("compaction")
        expect(msgs.some((m) => m.info.role === "assistant" && m.info.summary === true)).toBe(false)
      }),
    30_000,
  )
})
