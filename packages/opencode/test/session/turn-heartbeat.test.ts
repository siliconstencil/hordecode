// Parity with upstream reference packages/opencode/test/turn-heartbeat.test.ts.
//
//  runLoop must call SupervisorRegistryService.updateTurn once per model
// step. Session.create auto-registers the ("main") supervisor row with
// turn_count=0 and last_turn_time/time.updated pinned to registration. Without
// the per-step heartbeat (added at packages/opencode/src/session/prompt.ts
// right after `step++`, mirroring upstream session/prompt.ts:3431-3433) the
// orchestrator cannot tell a progressing child from a stalled one
// (turnCount frozen at 0, timestamps frozen for the whole turn).
//
// Drive a 2-step turn (tool call -> text) and assert the row's turn_count
// advanced past 0 and last_turn_time / time.updated moved forward from the
// values captured at registration.

